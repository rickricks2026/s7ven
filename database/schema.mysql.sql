CREATE TABLE settings (name VARCHAR(100) PRIMARY KEY,value TEXT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE users (id BIGINT PRIMARY KEY AUTO_INCREMENT,name VARCHAR(120) NOT NULL,email VARCHAR(190) NOT NULL UNIQUE,password_hash VARCHAR(255) NOT NULL,role VARCHAR(20) NOT NULL DEFAULT 'client',active INTEGER NOT NULL DEFAULT 1,created_at VARCHAR(19) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE products (id BIGINT PRIMARY KEY AUTO_INCREMENT,name VARCHAR(150) NOT NULL,category VARCHAR(40) NOT NULL,description TEXT NOT NULL,features TEXT NOT NULL,price DECIMAL(12,2) NULL,visible INTEGER NOT NULL DEFAULT 1,created_at VARCHAR(19) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE orders (id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,product_id BIGINT NOT NULL,product_name VARCHAR(150) NOT NULL,amount DECIMAL(12,2) NULL,status VARCHAR(30) NOT NULL DEFAULT 'requested',domain VARCHAR(253) NOT NULL,notes TEXT NOT NULL,created_at VARCHAR(19) NOT NULL,updated_at VARCHAR(19) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE licenses (id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,product_id BIGINT NOT NULL,order_id BIGINT NULL UNIQUE,domain VARCHAR(253) NOT NULL,key_hash VARCHAR(64) NOT NULL UNIQUE,status VARCHAR(20) NOT NULL DEFAULT 'active',expires_at VARCHAR(10) NULL,created_at VARCHAR(19) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tickets (id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,subject VARCHAR(200) NOT NULL,status VARCHAR(20) NOT NULL DEFAULT 'open',created_at VARCHAR(19) NOT NULL,updated_at VARCHAR(19) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE messages (id BIGINT PRIMARY KEY AUTO_INCREMENT,ticket_id BIGINT NOT NULL,user_id BIGINT NOT NULL,body TEXT NOT NULL,created_at VARCHAR(19) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE content (id BIGINT PRIMARY KEY AUTO_INCREMENT,kind VARCHAR(30) NOT NULL,title VARCHAR(180) NOT NULL,body TEXT NOT NULL,version VARCHAR(30) NOT NULL DEFAULT '',link VARCHAR(1000) NOT NULL DEFAULT '',image_url VARCHAR(1000) NOT NULL DEFAULT '',published INTEGER NOT NULL DEFAULT 0,created_at VARCHAR(19) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE leads (id BIGINT PRIMARY KEY AUTO_INCREMENT,name VARCHAR(120) NOT NULL,email VARCHAR(190) NOT NULL,server_name VARCHAR(150) NOT NULL,version VARCHAR(40) NOT NULL,plan VARCHAR(100) NOT NULL,body TEXT NOT NULL,status VARCHAR(20) NOT NULL DEFAULT 'new',created_at VARCHAR(19) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE files (id BIGINT PRIMARY KEY AUTO_INCREMENT,product_id BIGINT NULL,ticket_id BIGINT NULL,uploaded_by BIGINT NOT NULL,name VARCHAR(200) NOT NULL,size BIGINT NOT NULL,sha256 VARCHAR(64) NOT NULL,data LONGBLOB NOT NULL,created_at VARCHAR(19) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE audit (id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NULL,action VARCHAR(100) NOT NULL,details TEXT NOT NULL,created_at VARCHAR(19) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE attempts (id BIGINT PRIMARY KEY AUTO_INCREMENT,identity VARCHAR(64) NOT NULL,created_at VARCHAR(19) NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE INDEX idx_attempts ON attempts (identity,created_at);

CREATE INDEX idx_license_owner ON licenses (user_id,product_id,status);

CREATE INDEX idx_ticket_owner ON tickets (user_id,status);

CREATE INDEX idx_order_owner ON orders (user_id,status);

CREATE INDEX idx_messages ON messages (ticket_id,id);

CREATE INDEX idx_files_product ON files (product_id);

CREATE INDEX idx_files_ticket ON files (ticket_id);

CREATE INDEX idx_content_public ON content (kind,published);

