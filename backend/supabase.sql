create table public.app_admins (
 user_id uuid primary key references auth.users(id) on delete cascade
);
create or replace function public.is_admin() returns boolean
 language sql stable security definer set search_path = public, pg_temp
 as $$ select exists (select 1 from public.app_admins where user_id = auth.uid()); $$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create table public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 display_name text not null check(char_length(display_name) between 1 and 100),
 email text not null,
 created_at timestamptz not null default now()
);
create or replace function public.handle_new_user() returns trigger
 language plpgsql security definer set search_path = public, pg_temp as $$
 begin
 insert into public.profiles(id,display_name,email)
 values(new.id,coalesce(nullif(left(trim(new.raw_user_meta_data->>'display_name'),100),''),'Cliente'),coalesce(new.email,''));
 return new;
 end; $$;
revoke all on function public.handle_new_user() from public;
create trigger s7ven_new_user after insert on auth.users for each row execute function public.handle_new_user();
insert into public.profiles(id,display_name,email)
 select id,coalesce(nullif(left(trim(raw_user_meta_data->>'display_name'),100),''),'Cliente'),coalesce(email,'') from auth.users
 on conflict(id) do nothing;
create or replace function public.sync_profile_email() returns trigger
 language plpgsql security definer set search_path = public, pg_temp as $$
 begin update public.profiles set email=coalesce(new.email,'') where id=new.id; return new; end; $$;
revoke all on function public.sync_profile_email() from public;
create trigger s7ven_email_update after update of email on auth.users for each row execute function public.sync_profile_email();

