-- Solicitação: nome e preço vêm do banco, nunca do navegador.
create or replace function public.request_product(p_product_id bigint,p_domain text,p_notes text) returns bigint
 language plpgsql security definer set search_path=public,pg_temp as $$
 declare p public.products; oid bigint;
 begin
 if auth.uid() is null then raise exception 'authentication_required'; end if;
 if p_domain is null or p_domain !~ '^[a-z0-9]([a-z0-9.-]*[a-z0-9])?\.[a-z]{2,63}$' or char_length(p_domain)>253 then raise exception 'invalid_domain'; end if;
 if p_notes is null or char_length(p_notes)>5000 then raise exception 'invalid_notes'; end if;
 -- Serializar limites por conta para evitar requisições simultâneas excedentes.
 perform 1 from public.profiles where id=auth.uid() for update;
 if (select count(*) from public.orders where user_id=auth.uid() and created_at>now()-interval '1 hour')>=15 then raise exception 'rate_limit'; end if;
 select * into p from public.products where id=p_product_id and visible;
 if not found then raise exception 'product_unavailable'; end if;
 insert into public.orders(user_id,product_id,product_name,amount,domain,notes) values(auth.uid(),p.id,p.name,p.price,p_domain,p_notes) returning id into oid;
 return oid;
 end; $$;
create or replace function public.create_ticket(p_subject text,p_body text) returns bigint
 language plpgsql security definer set search_path=public,pg_temp as $$
 declare tid bigint;
 begin
 if auth.uid() is null then raise exception 'authentication_required'; end if;
 if p_subject is null or char_length(trim(p_subject)) not between 1 and 160 or p_body is null or char_length(trim(p_body)) not between 5 and 6000 then raise exception 'invalid_message'; end if;
 perform 1 from public.profiles where id=auth.uid() for update;
 if (select count(*) from public.tickets where user_id=auth.uid() and created_at>now()-interval '1 hour')>=15 then raise exception 'rate_limit'; end if;
 insert into public.tickets(user_id,subject) values(auth.uid(),trim(p_subject)) returning id into tid;
 insert into public.messages(ticket_id,user_id,body) values(tid,auth.uid(),trim(p_body));
 return tid;
 end; $$;
create or replace function public.reply_ticket(p_ticket_id bigint,p_body text,p_status text) returns void
 language plpgsql security definer set search_path=public,pg_temp as $$
 declare t public.tickets; staff boolean;
 begin
 if auth.uid() is null then raise exception 'authentication_required'; end if;
 staff=public.is_admin();
 select * into t from public.tickets where id=p_ticket_id for update;
 if not found or (not staff and t.user_id<>auth.uid()) then raise exception 'ticket_unavailable'; end if;
 if not staff and t.status='closed' then raise exception 'ticket_closed'; end if;
 if p_body is null or char_length(trim(p_body)) not between 2 and 6000 then raise exception 'invalid_message'; end if;
 if staff and p_status not in ('answered','closed') then raise exception 'invalid_status'; end if;
 perform 1 from public.profiles where id=auth.uid() for update;
 if (select count(*) from public.messages where user_id=auth.uid() and created_at>now()-interval '1 hour')>=60 then raise exception 'rate_limit'; end if;
 insert into public.messages(ticket_id,user_id,body) values(t.id,auth.uid(),trim(p_body));
 update public.tickets set status=case when staff then p_status else 'open' end,updated_at=now() where id=t.id;
 end; $$;
create or replace function public.admin_update_order(p_order_id bigint,p_amount numeric,p_status text,p_payment_verified boolean) returns void
 language plpgsql security definer set search_path=public,pg_temp as $$
 begin
 if not public.is_admin() then raise exception 'permission_denied'; end if;
 if p_status is null or p_status not in ('requested','quoted','paid','delivered','cancelled') or p_amount<0 then raise exception 'invalid_order'; end if;
 if p_status in ('paid','delivered') and (p_amount is null or p_payment_verified is not true) then raise exception 'payment_verification_required'; end if;
 update public.orders set amount=p_amount,status=p_status,updated_at=now() where id=p_order_id;
 if not found then raise exception 'order_not_found'; end if;
 end; $$;
revoke all on function public.request_product(bigint,text,text),public.create_ticket(text,text),public.reply_ticket(bigint,text,text),public.admin_update_order(bigint,numeric,text,boolean) from public;
grant execute on function public.request_product(bigint,text,text),public.create_ticket(text,text),public.reply_ticket(bigint,text,text),public.admin_update_order(bigint,numeric,text,boolean) to authenticated;

